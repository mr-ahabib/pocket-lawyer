export function actKey(title: string): ActKey | null {
  const tl = title.toLowerCase();
  if (/penal code/.test(tl)) return 'penal';
  if (/code of criminal procedure/.test(tl)) return 'crpc';
  if (/negotiable instruments act/.test(tl)) return 'ni';
  if (/^the contract act/.test(tl)) return 'contract';
  if (/evidence act/.test(tl)) return 'evidence';
  if (/transfer of property act/.test(tl)) return 'tpa';
  if (/limitation act/.test(tl)) return 'limitation';
  if (/specific relief act/.test(tl)) return 'srelief';
  if (/^the registration act/.test(tl)) return 'registration';
  if (/code of civil procedure/.test(tl)) return 'cpc';
  if (/constitution of the people/.test(tl)) return 'constitution_en';
  return null;
}

/** Bangla name for an act title (English majors mapped; Bangla titles returned as-is). */
export function actNameBn(title: string): string {
  const k = actKey(title);
  return k ? ACT_BN[k] : title;
}

